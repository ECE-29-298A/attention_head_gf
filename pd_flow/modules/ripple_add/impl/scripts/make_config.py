#!/usr/bin/env python3
"""Build the Phase 4 LibreLane block config from the approved Phase 3 template.

Usage: make_config.py N OUT.json

Starts from layout_plan/out/block_n<N>_librelane.json (untested template, deviations stated in its
//deviation_* keys) and applies only the changes listed in CHANGES below. Every change is recorded
in the output under "//phase4_changes" so the config documents itself.

Placement stays FIRM from block_n<N>.cfg (MACRO_PLACEMENT_CFG); routing stays automatic.
"""
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
PLAN_OUT = HERE.parents[1] / "layout_plan" / "out"
LIBDIR = "pdk_dir::libs.ref/gf180mcu_fd_sc_mcu7t5v0/lib/gf180mcu_fd_sc_mcu7t5v0__"

# Changes against the template, with the reason for each. Nothing here moves a cell or a route.
CHANGES = {
    # Same supply/corner set as the shipped TT gf180 flow (tt/tech.py GF180MCUDTech), so block
    # numbers are comparable with the chip: the 5 V library characterised at 3.3 V.
    "VDD_PIN": ("VPWR", "TT power-net names, so the block's rails/pins match the chip"),
    "GND_PIN": ("VGND", "same"),
    # (tt/tech.py also sets VDD_PIN_VOLTAGE and LIB_SYNTH/FASTEST/SLOWEST; LibreLane 3.0.14
    # reports those keys as removed/unknown, so only LIB and the corners are carried over.)
    "DEFAULT_CORNER": ("nom_tt_025C_3v30", "TT gf180 corner set"),
    "STA_CORNERS": ([f"{rc}_{c}" for rc in ("nom", "min", "max")
                     for c in ("tt_025C_3v30", "ss_125C_3v00", "ff_n40C_3v60")],
                    "TT gf180 corner set"),
    "LIB": ({"*_tt_025C_3v30": [LIBDIR + "tt_025C_3v30.lib"],
             "*_ss_125C_3v00": [LIBDIR + "ss_125C_3v00.lib"],
             "*_ff_n40C_3v60": [LIBDIR + "ff_n40C_3v60.lib"]}, "TT gf180 corner set"),
    # Pin geometry as in the chip config (FP_IO_HLENGTH/VLENGTH 2 there).
    "IO_PIN_H_LENGTH": (2, "chip config FP_IO_HLENGTH"),
    "IO_PIN_V_LENGTH": (2, "chip config FP_IO_VLENGTH"),
    # Elaborate-only keeps the netlist's `assign c[0] = cin` alias as an assign statement, which
    # Checker.NetlistAssignStatements rejects (first run, 2026-11-26). Full synthesis runs
    # opt_clean, which merges the alias; the pre-mapped cell instances are Liberty cells that ABC
    # does not touch. check_netlist.py proves the post-synthesis and final netlists have the same
    # 22 instances, masters and pin connections as the approved netlist.
    "SYNTH_ELABORATE_ONLY": (False, "remove the c[0]=cin alias assign (netlist-format check), "
                             "instances verified unchanged by check_netlist.py"),
    # PDN: the template's chip offset (16.32 um from the core edge) puts the 4.9 um VPWR/VGND
    # pair past the 20.72 um core (PDN-0185, run 2). Centre the single pair on the core instead:
    # (20.72 - 4.9) / 2 = 7.91 um. Stripes over the column were already the template's stated
    # deviation_1_pdn; this fixes only their x position. Pitch unchanged (one pair fits).
    "PDN_VOFFSET": (7.91, "single M4 pair centred on the 20.72 um core (PDN-0185 at 16.32)"),
    # Row-aligned pins (make_pin_template.py): CustomIOPlacement centres the pins instead of
    # putting bit i's pins in row i (run r1: a[0] at y 22.68 um). The template only sets pin
    # coordinates (same die, same sides and order as block_n<N>_pins.cfg).
    "FP_DEF_TEMPLATE": ("dir::pins_template.def", "bit i's pins inside relative row i (PLAN 5.5)"),
    "FP_TEMPLATE_MATCH_MODE": ("strict", "template pin set must equal the design's"),
    # Keep the flow's own KLayout-vs-Magic GDS XOR (a cross-check, cheap at this size).
    "RUN_KLAYOUT_XOR": (True, "GDS cross-check between Magic and KLayout stream-out"),
}


def main():
    n, out = int(sys.argv[1]), Path(sys.argv[2])
    tpl = json.loads((PLAN_OUT / f"block_n{n}_librelane.json").read_text())
    cfg = dict(tpl)
    log = {}
    for k, (v, why) in CHANGES.items():
        log[k] = {"template": tpl.get(k, "<unset>"), "phase4": v, "why": why}
        cfg[k] = v
    cfg["//phase4_changes"] = log
    cfg["//phase4"] = ("Generated by impl/scripts/make_config.py from layout_plan/out/"
                       f"block_n{n}_librelane.json. Placement FIRM (MACRO_PLACEMENT_CFG), "
                       "routing automatic (OpenROAD GRT/DRT), no hand routing (D4).")
    out.write_text(json.dumps(cfg, indent=1) + "\n")
    print(f"wrote {out} ({len(log)} changes)")


if __name__ == "__main__":
    main()
