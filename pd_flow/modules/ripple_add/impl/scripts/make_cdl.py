#!/usr/bin/env python3
"""Schematic (SPICE/CDL) view of the hardened block, built from the PDK cell SPICE.

Usage: make_cdl.py PNL.v OUT [cdl|spice] [--sub NAME] [--omit-empty]

  --omit-empty  leave out instances of device-less masters (endcap, fill_N): KLayout drops their
        layout circuits (no devices), so the schematic must not reference them either. Their
        tap connections remain in the layout and are part of the extracted parent nets.

  --sub NAME  connect every cell's VPW (p-substrate body) to a separate port NAME instead of VGND.
        Needed for the PDK KLayout LVS deck: it extracts the substrate as one global net
        (`sub = polygon_layer`, connect_global(sub, $lvs_sub)) that is never merged with the ptap /
        VSS net, so nfet bodies come out on a net of their own. Use with -rd lvs_sub=NAME.

  cdl   (default) cell subcircuits from libs.ref/.../cdl/gf180mcu_fd_sc_mcu7t5v0.cdl: MOSFETs as
        M elements, the PDK's LVS view (KLayout LVS reads M as devices).
  spice cell subcircuits from libs.ref/.../spice/gf180mcu_fd_sc_mcu7t5v0.spice: MOSFETs as X calls of
        the ngspice model subcircuits nfet_05v0/pfet_05v0 (simulation view).

The top subcircuit `ripple_add` instantiates every cell of the powered netlist (logic cells and the
physical endcap/fill/fillcap cells, which LVS must also see because fillcap has transistors). Cell
pins are taken in the PDK SPICE subckt order; power pins follow the flow's connections
(VDD,VNW -> VPWR; VSS,VPW -> VGND). The PDK cell subcircuits are appended verbatim from
the chosen PDK library file (only the masters used).
Port order of `ripple_add`: a[0..N-1] b[0..N-1] cin s[0..N-1] VPWR VGND.
"""
import re
import sys
from pathlib import Path

LIBREF = Path("/Users/samuelzhang/ttsetup/pdk/ciel/gf180mcu/versions/"
              "54435919abffb937387ec956209f9cf5fd2dfbee/gf180mcuD/libs.ref/gf180mcu_fd_sc_mcu7t5v0")
PDK_LIB = {"cdl": LIBREF / "cdl/gf180mcu_fd_sc_mcu7t5v0.cdl",
           "spice": LIBREF / "spice/gf180mcu_fd_sc_mcu7t5v0.spice"}
PDK_SPICE = None
POWER = {"VDD": "VPWR", "VNW": "VPWR", "VSS": "VGND", "VPW": "VGND"}


def pdk_subckts():
    text = PDK_SPICE.read_text()
    assert text.count(".SUBCKT") or text.count(".subckt")
    out = {}
    for m in re.finditer(r"^\.SUBCKT (\S+) ([^\n]*)\n(.*?)^\.ENDS", text, re.S | re.M | re.I):
        out[m.group(1)] = (m.group(2).split(), m.group(0))
    return out


def main():
    global PDK_SPICE
    pnl, outp = Path(sys.argv[1]), Path(sys.argv[2])
    args = sys.argv[3:]
    sub_net = None
    omit_empty = "--omit-empty" in args
    args = [a for a in args if a != "--omit-empty"]
    if "--sub" in args:
        sub_net = args[args.index("--sub") + 1]
        del args[args.index("--sub"):args.index("--sub") + 2]
    PDK_SPICE = PDK_LIB[args[0] if args else "cdl"]
    power = dict(POWER)
    if sub_net:
        power["VPW"] = sub_net
    text = re.sub(r"//.*", "", pnl.read_text())
    sub = pdk_subckts()
    n = int(re.search(r"input \[(\d+):0\] a;", text).group(1)) + 1
    insts = []
    for m in re.finditer(r"(gf180mcu_fd_sc_mcu7t5v0__\w+)\s+(\\?\S+)\s*\((.*?)\);", text, re.S):
        master, name, conns = m.group(1), m.group(2).replace("\\", "").strip(), m.group(3)
        pins = {p: v.replace("\\", "").replace(" ", "")
                for p, v in re.findall(r"\.(\w+)\s*\(\s*([^()]*?)\s*\)", conns)}
        order = sub[master][0]
        nets = []
        for p in order:
            if p == "VPW" and sub_net:
                nets.append(sub_net)
            elif p in pins:
                nets.append(pins[p])
            elif p in POWER:           # endcap's VNW/VPW are not in the LEF/pnl
                nets.append(POWER[p])
            else:
                raise SystemExit(f"{name}: pin {p} of {master} unconnected")
        for p, v in pins.items():
            if p in POWER:
                assert v == POWER[p], (name, p, v)
        body = sub[master][1].splitlines()[1:-1]
        if omit_empty and not any(l.strip() and not l.startswith("*") for l in body):
            continue
        insts.append((name, master, nets))
    ports = [f"a[{i}]" for i in range(n)] + [f"b[{i}]" for i in range(n)] + ["cin"] + \
            [f"s[{i}]" for i in range(n)] + ["VPWR", "VGND"] + ([sub_net] if sub_net else [])
    lines = [f"* ripple_add N={n}: schematic from {pnl.name} + PDK cell SPICE "
             f"({PDK_SPICE.name}); generated by impl/scripts/make_cdl.py", ""]
    lines.append(".SUBCKT ripple_add " + " ".join(ports))
    for name, master, nets in insts:
        safe = "X" + re.sub(r"[\[\].]", "_", name)
        lines.append(f"{safe} {' '.join(nets)} {master}")
    lines += [".ENDS ripple_add", ""]
    for master in sorted({m for _, m, _ in insts}):
        lines += [sub[master][1], ""]
    outp.write_text("\n".join(lines))
    print(f"wrote {outp}: {len(insts)} instances, masters {sorted({m for _, m, _ in insts})}")


if __name__ == "__main__":
    main()
