#!/usr/bin/env python3
"""Cell models for the gate-level top test with defined flop power-up state.

Usage: make_gl_models.py OUT.v {zero|random} [--power-pins]

The chip has no asynchronously reset flops: all 329 flops are dffq_1/2/4, and the datapath flops are
deliberately not reset (reset is synchronous, through D logic, on the control state only). In
Icarus the PDK UDP flop model powers up X, and gate-level X-pessimism lets that X reach uio_out[3]
(SCK) one clock after reset release, so test/top/run.py fails at 31 ns on every netlist (also the
baseline: layout_plan/chip_power/gl_top_test_base_probe.log). Silicon flops power up 0 or 1, never X.

This file = the PDK functional models (libs.ref/.../verilog/gf180mcu_fd_sc_mcu7t5v0.v and
primitives.v, copied, with only the dffq_1/_2/_4 modules removed) + behavioural dffq_1/_2/_4 with the
same ports and function (Q <= D on CLK rise) whose state is initialised at t = 0 to 0 ("zero") or to
$urandom bits ("random"), ignoring the X->1 clock "edge" at t = 0 (cocotb starts clk high; with the
PDK model or a plain always block every flop captures the unsettled X there). Nothing in the PDK, src/ or test/ is changed.
"""
import re
import sys
from pathlib import Path

V = Path("/Users/samuelzhang/ttsetup/pdk/ciel/gf180mcu/versions/54435919abffb937387ec956209f9cf5fd2dfbee/"
         "gf180mcuD/libs.ref/gf180mcu_fd_sc_mcu7t5v0/verilog")
DFF = ("gf180mcu_fd_sc_mcu7t5v0__dffq_1", "gf180mcu_fd_sc_mcu7t5v0__dffq_2", "gf180mcu_fd_sc_mcu7t5v0__dffq_4")


def strip_modules(text, names):
    out, removed = [], []
    i = 0
    pat = re.compile(r"^(`ifdef USE_POWER_PINS\s*\n)?module (\w+)\(", re.M)
    while True:
        m = pat.search(text, i)
        if not m:
            out.append(text[i:])
            break
        name = m.group(2)
        if name in names:
            # the cell module is wrapped as: `ifdef USE_POWER_PINS module X(..p..); `else module X(..);
            # `endif ... endmodule
            start = m.start()
            end = text.index("endmodule", m.end()) + len("endmodule")
            out.append(text[i:start])
            removed.append(name)
            i = end
        else:
            out.append(text[i:m.end()])
            i = m.end()
    return "".join(out), removed


def main():
    out, mode = Path(sys.argv[1]), sys.argv[2]
    power = "--power-pins" in sys.argv
    lib = (V / "gf180mcu_fd_sc_mcu7t5v0.v").read_text()
    lib, removed = strip_modules(lib, set(DFF))
    assert sorted(removed) == sorted(DFF), removed
    init = "1'b0" if mode == "zero" else "$urandom % 2"
    hdr = [f"// Generated by impl/scripts/make_gl_models.py ({mode} flop init, power pins {power}).",
           "`timescale 1ns/1ps", "`define FUNCTIONAL"]
    if power:
        hdr.append("`define USE_POWER_PINS")
    models = []
    for d in DFF:
        ports = "CLK, D, Q" + (", VDD, VSS, VNW, VPW" if power else "")
        models.append(f"""module {d}( {ports} );
input CLK, D;
output Q;
{"inout VDD, VSS, VNW, VPW;" if power else ""}
reg q;
initial q = {init};
// cocotb starts clk high at t = 0, so Icarus sees an X->1 posedge at t = 0, racing the initial
// block and the combinational settle; that edge is not a real clock edge and is ignored.
always @(posedge CLK) if ($time != 0) q <= D;
assign Q = q;
endmodule
""")
    text = "\n".join(hdr) + "\n" + (V / "primitives.v").read_text() + "\n" + lib + "\n" + "\n".join(models)
    out.write_text(text)
    print(f"wrote {out}: removed {removed}, init={init}")


if __name__ == "__main__":
    main()
