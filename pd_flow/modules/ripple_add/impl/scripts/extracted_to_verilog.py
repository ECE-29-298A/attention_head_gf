#!/usr/bin/env python3
"""Gate-level Verilog of the block as extracted from the layout.

Usage: extracted_to_verilog.py EXTRACTED.spice N OUT.v

EXTRACTED.spice is Magic's cell-level extraction of the final GDS (the netlist the flow's Netgen
LVS reads: final/spice/ripple_add.spice). Every X instance of a logic cell becomes a Verilog cell
instance with its pins taken from the black-box .subckt pin order; nets keep the extracted names
(mapped to legal identifiers); physical cells with only power pins (endcap, fill, fillcap) and the
power pins themselves are dropped. The result is what the frozen gate contract runs on, so the
contract sees the connectivity of the layout, not the netlist that was fed to the flow.
"""
import re
import sys
from pathlib import Path

POWER = {"VDD", "VSS", "VNW", "VPW"}


def main():
    src, n, out = Path(sys.argv[1]), int(sys.argv[2]), Path(sys.argv[3])
    text = src.read_text().replace("\n+", " ")
    subs = {m.group(1): m.group(2).split()
            for m in re.finditer(r"^\.subckt (\S+) ([^\n]*)$", text, re.M)}
    top = subs.pop("ripple_add")
    body = re.search(r"^\.subckt ripple_add [^\n]*\n(.*?)^\.ends", text, re.S | re.M).group(1)
    ports = {f"a[{i}]" for i in range(n)} | {f"b[{i}]" for i in range(n)} | {"cin"} | \
            {f"s[{i}]" for i in range(n)}
    assert set(top) == ports | {"VPWR", "VGND"}, sorted(set(top) ^ (ports | {"VPWR", "VGND"}))

    def ident(net):
        net = net.replace("\\", "")
        if net in ports:
            return net
        return "n_" + re.sub(r"[^A-Za-z0-9_]", "_", net)

    insts, wires = [], set()
    for line in body.splitlines():
        t = line.split()
        if not t or not t[0].startswith("X"):
            continue
        name, nets, master = t[0][1:].replace("\\", ""), t[1:-1], t[-1]
        pins = subs[master]
        assert len(pins) == len(nets), (name, master)
        conn = [(p, ident(v)) for p, v in zip(pins, nets) if p not in POWER]
        if not conn:
            continue
        for _, v in conn:
            if v not in ports:
                wires.add(v)
        insts.append((master, name, conn))
    lines = [f"// ripple_add N={n}: gate-level netlist EXTRACTED FROM THE LAYOUT (Magic cell-level",
             f"// extraction of the final GDS, {src.name}); generated by impl/scripts/extracted_to_verilog.py.",
             "// Physical-only cells (endcap/fill/fillcap) and power pins omitted.",
             "module ripple_add (", f"    input  wire [{n-1}:0] a,", f"    input  wire [{n-1}:0] b,",
             "    input  wire        cin,", f"    output wire [{n-1}:0] s", ");"]
    lines += [f"    wire {w};" for w in sorted(wires)]
    for master, name, conn in sorted(insts, key=lambda x: x[1]):
        iname = re.sub(r"[^A-Za-z0-9_]", "_", name)
        lines.append(f"    {master} {iname} (" + ", ".join(f".{p}({v})" for p, v in conn) + ");")
    lines += ["endmodule", ""]
    out.write_text("\n".join(lines))
    print(f"wrote {out}: {len(insts)} logic instances, {len(wires)} internal nets")


if __name__ == "__main__":
    main()
