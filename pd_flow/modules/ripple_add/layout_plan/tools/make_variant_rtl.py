#!/usr/bin/env python3
"""Emit a candidate chip RTL directory: the 7 shipped files from the golden copy, with only
ripple_add.v replaced by a cell-structured, simulation-guarded version.

Usage: make_variant_rtl.py <variant> <out_dir>
Variants (per instantiated width; 'abc' = golden behavioural body, ABC maps it in context):
  base      : N=22 abc,      N=12 abc      (golden file copied byte-for-byte)
  addf1     : N=22 addf1,    N=12 addf1    (pure addf_1 chain, CO of MSB left open)
  hyb       : N=22 addf1x3,  N=12 addf1x3  (addf_1 chain, MSB = xor3_1: no unused carry)
  hyb22     : N=22 addf1x3,  N=12 abc      (cells only on the 22-bit adder)
  hybcos    : 'hyb' with the generate label renamed (cosmetic: harden noise of the cell family)
  abcfrozen : module-level ABC netlists (verif/gate/netlists, 95 + 50 cells) frozen as cells
  n03, n04  : Phase 2 cosmetic rewrites of the golden RTL (opt/noise/): harden noise of the ABC family
Guard: the cell branch is compiled only under `SYNTHESIS (Yosys defines it by default);
simulators and the Verilator linter see the golden behavioural body.
"""
import os, shutil, sys
GOLD = os.path.join(os.path.dirname(os.path.abspath(__file__)), "../../../../baseline/original_rtl")
FILES = ["project.v", "attention_controller.sv", "mac_unit.v", "ripple_add.v", "max_reg.v",
         "exp_lut.v", "divider.v"]
VARIANTS = {"base": None, "addf1": ("addf1", "addf1"), "hyb": ("addf1x3", "addf1x3"),
            "hyb22": ("addf1x3", "abc"), "hybcos": ("addf1x3", "addf1x3"),
            "abcfrozen": "frozen", "n03": "noise:n03_swap_sum.v", "n04": "noise:n04_swap_or.v"}
P = "gf180mcu_fd_sc_mcu7t5v0__"

GOLDEN_BODY = """    wire [N:0] c;
    assign c[0] = cin;
    genvar i;
    generate
        for (i = 0; i < N; i = i + 1) begin : fa
            assign s[i]     = a[i] ^ b[i] ^ c[i];
            assign c[i + 1] = (a[i] & b[i]) | (c[i] & (a[i] ^ b[i]));
        end
    endgenerate"""

def cell_chain(kind, indent):
    t = " " * indent
    if kind == "addf1":
        return f"""{t}for (i = 0; i < N; i = i + 1) begin : bitslice
{t}    {P}addf_1 u_fa (.A(a[i]), .B(b[i]), .CI(c[i]), .S(s[i]), .CO(c[i + 1]));
{t}end"""
    if kind == "addf1x3":
        return f"""{t}for (i = 0; i < N - 1; i = i + 1) begin : bitslice
{t}    {P}addf_1 u_fa (.A(a[i]), .B(b[i]), .CI(c[i]), .S(s[i]), .CO(c[i + 1]));
{t}end
{t}{P}xor3_1 u_msb_x3 (.A1(a[N-1]), .A2(b[N-1]), .A3(c[N-1]), .Z(s[N-1]));
{t}assign c[N] = 1'b0; // no carry out: the MSB is a 3-input XOR"""
    raise ValueError(kind)

def emit_frozen():
    import re
    mods = []
    for n in (22, 12):
        t = open(os.path.join(GOLD, f"../../modules/ripple_add/verif/gate/netlists/ripple_add_gf180_n{n}.v")).read()
        t = re.sub(r"/\*.*?\*/", "", t, flags=re.S).replace("module ripple_add(", f"module ripple_add_abc{n}(")
        mods.append(t.strip())
    return f"""// Candidate (layout_plan, variant 'abcfrozen'): module-level ABC netlists frozen as cells.
// Generated by pd_flow/modules/ripple_add/layout_plan/tools/make_variant_rtl.py. Do not edit.
module ripple_add #(parameter N = 16) (
    input  wire [N-1:0] a,
    input  wire [N-1:0] b,
    input  wire         cin,
    output wire [N-1:0] s
);
`ifdef SYNTHESIS
    generate
        if (N == 22) begin : frz
            ripple_add_abc22 u (.a(a), .b(b), .cin(cin), .s(s));
        end else begin : frz
            ripple_add_abc12 u (.a(a), .b(b), .cin(cin), .s(s));
        end
    endgenerate
`else
{GOLDEN_BODY}
`endif
endmodule

`ifdef SYNTHESIS
{chr(10).join(mods)}
`endif
"""

def emit(variant):
    if VARIANTS[variant] == "frozen":
        return emit_frozen()
    n22, n12 = VARIANTS[variant]
    if n22 == n12:
        body = cell_chain(n22, 8)
    else:
        def br(k):
            return GOLDEN_BODY_GEN if k == "abc" else cell_chain(k, 12)
        body = (f"        if (N == 22) begin : impl22\n{br(n22)}\n        end else begin : impl_other\n"
                f"{br(n12)}\n        end")
    return f"""// Candidate (layout_plan, variant '{variant}'): ripple_add as instantiated GF180 7-track cells.
// Generated by pd_flow/modules/ripple_add/layout_plan/tools/make_variant_rtl.py. Do not edit.
// The cell branch is used only under `SYNTHESIS; simulation and lint see the golden body.
module ripple_add #(parameter N = 16) (
    input  wire [N-1:0] a,
    input  wire [N-1:0] b,
    input  wire         cin,
    output wire [N-1:0] s
);
`ifdef SYNTHESIS
    wire [N:0] c;
    assign c[0] = cin;
    genvar i;
    generate
{body}
    endgenerate
`else
{GOLDEN_BODY}
`endif
endmodule
"""

GOLDEN_BODY_GEN = """            for (i = 0; i < N; i = i + 1) begin : fa
                assign s[i]     = a[i] ^ b[i] ^ c[i];
                assign c[i + 1] = (a[i] & b[i]) | (c[i] & (a[i] ^ b[i]));
            end"""

if __name__ == "__main__":
    v, out = sys.argv[1], sys.argv[2]
    os.makedirs(out, exist_ok=True)
    for f in FILES:
        shutil.copy(os.path.join(GOLD, f), os.path.join(out, f))
    if isinstance(VARIANTS[v], str) and VARIANTS[v].startswith("noise:"):
        shutil.copy(os.path.join(GOLD, "../../modules/ripple_add/opt/noise", VARIANTS[v][6:]),
                    os.path.join(out, "ripple_add.v"))
    elif VARIANTS[v] is not None:
        t = emit(v)
        if v == "hybcos":
            t = t.replace(": bitslice", ": bs")
        open(os.path.join(out, "ripple_add.v"), "w").write(t)
    print("wrote", out)
