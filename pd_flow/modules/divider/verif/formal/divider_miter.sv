// seq_eq item (SPEC.md section 4, amendment A-1): sequential equivalence miter of the golden
// (module divider_gold, the snapshot renamed by run_all.sh) against the candidate (module
// divider), both driven by the same free inputs.
//   - Anchored on R13: rst_n is forced low in cycle 0 STRUCTURALLY (rst = rst_n_in && !first,
//     first = an initialised harness register), not by an assumption. The power-up state of
//     both instances is free, so cycle 0 stands for "any state at the first reset edge".
//   - From cycle 1 on, every output port is compared: a_eq.
//   - There are NO assumptions (assume, restrict, anyconst, anyseq) anywhere.
//   - Optional candidate-supplied lemmas (strengthening invariants over gold.* and cand.*)
//     are included from seq_lemmas.vh, generated by formal/lemma_prep.py from the lemma file.
//     They are ASSERTIONS, proven together with a_eq (never assumed), so the item stays sound
//     whoever writes them; a lemma that does not hold makes the item fail.
// -DP11: configuration 11 (LATCH_DENOMINATOR = CHECK_INVALID = 1), else 00.
// fv_mode.vh defines GATE for a gate-level candidate (no parameters).
`include "fv_mode.vh"
module divider_miter (
    input wire               clk,
    input wire               rst_n_in,
    input wire               start,
    input wire signed [19:0] sum_in,
    input wire        [11:0] denominator,
    input wire               shift
);
`ifdef P11
    localparam LD = 1, CI = 1;
`else
    localparam LD = 0, CI = 0;
`endif
    reg first = 1'b1;                        // observer: cycle 0
    reg seen  = 1'b0;                        // observer: the cycle-0 reset edge has been taken
    always @(posedge clk) begin
        first <= 1'b0;
        seen  <= 1'b1;
    end
    wire rst_n = rst_n_in && !first;         // reset in cycle 0, free afterwards

    wire g_busy, g_done, c_busy, c_done;
    wire signed [11:0] g_result, c_result;
    divider_gold #(.LATCH_DENOMINATOR(LD), .CHECK_INVALID(CI)) gold (.clk(clk), .rst_n(rst_n),
        .start(start), .sum_in(sum_in), .denominator(denominator), .shift(shift),
        .busy(g_busy), .done(g_done), .result(g_result));
`ifdef GATE
    divider cand (.clk(clk), .rst_n(rst_n), .start(start), .sum_in(sum_in), .denominator(denominator),
        .shift(shift), .busy(c_busy), .done(c_done), .result(c_result));
`else
    divider #(.LATCH_DENOMINATOR(LD), .CHECK_INVALID(CI)) cand (.clk(clk), .rst_n(rst_n),
        .start(start), .sum_in(sum_in), .denominator(denominator), .shift(shift),
        .busy(c_busy), .done(c_done), .result(c_result));
`endif

    always @* if (seen) begin
`ifdef SANITY_EQ
        a_wrong_eq: assert (c_result == g_result + 12'sd1);   // negative control: must be refuted
`else
        a_eq: assert (c_busy == g_busy && c_done == g_done && c_result == g_result);
`endif
    end

`include "seq_lemmas.vh"
endmodule
