#!/usr/bin/env python3
"""Write tables.md from raw outputs only: chip_runs/harden_table.json (scrape_harden.py, raw metrics.json),
the golden cosmetic-noise hardens of ripple_add Phase 3 (n03, n04: same flow, same day), chip_runs/netlen.json,
and the shipped-flow synthesis stats (statdiff.py logic)."""
import json, os, subprocess, sys
H = os.path.dirname(os.path.abspath(__file__)) + "/.."
t = json.load(open(f"{H}/chip_runs/harden_table.json"))
ra = json.load(open(f"{H}/../../ripple_add/layout_plan/chip_runs/harden_table.json"))
nl = json.load(open(f"{H}/chip_runs/netlen.json"))
runs = [("baseline (c) free", t["baseline_stored"], "base"), ("noise n03 (golden cosmetic)", ra["n03"], None),
        ("noise n04 (golden cosmetic)", ra["n04"], None), ("(b) b_m: M flops fixed", t["b_m"], "b_m"),
        ("(b) b_ms: M + S flops fixed", t["b_ms"], "b_ms"), ("(a) a_sdff: block fixed", t["a_sdff"], "a_sdff")]
b = t["baseline_stored"]
L = ["# max_reg Phase 3: chip-level tables (generated by tools/make_tables.py; do not edit)", "",
     "Full hardens, shipped config plus only the overlay named in PLAN.md. Raw sources: `chip_runs/<tag>/harden/metrics.json`;",
     "noise rows: `../../ripple_add/layout_plan/chip_runs/{n03,n04}/harden/metrics.json`. Power = metrics `power__total` (vectorless).", "",
     "| Run | Std-cell µm² | Δ | ss WNS (max) ns | tt / ff WNS ns | Hold ss/tt/ff ns | Slew/Cap/Fanout | Power mW | Wire µm | Repair-buffer µm² | DRC/LVS/antenna |",
     "|---|---:|---:|---:|---|---|---|---:|---:|---:|---|"]
for name, r, tag in runs:
    a = r["design__instance__area__stdcell"]
    L.append(f"| {name} | {a:,.1f} | {a - b['design__instance__area__stdcell']:+,.1f} | {r['setup_ws:max_ss_125C_3v00']:.2f} | "
             f"{r['setup_ws:max_tt_025C_3v30']:.2f} / {r['setup_ws:max_ff_n40C_3v60']:.2f} | "
             f"{r['hold_ws:max_ss_125C_3v00']:.3f} / {r['hold_ws:max_tt_025C_3v30']:.3f} / {r['hold_ws:max_ff_n40C_3v60']:.3f} | "
             f"{r['design__max_slew_violation__count']}/{r['design__max_cap_violation__count']}/{r['design__max_fanout_violation__count']} | "
             f"{r['power__total'] * 1e3:.3f} | {r['route__wirelength']:,} | {r['design__instance__area__class:timing_repair_buffer']:,.1f} | "
             f"{r['route__drc_errors']}/{r['design__lvs_error__count']}/{r['route__antenna_violation__count']} |")
L += ["", "Noise band (golden rewrites base, n03, n04): std-cell 46,819.2–47,220.9 µm²; ss WNS 38.21–42.90 ns; slew/cap/fanout 260–381 / 1–2 / 11–13; "
      "power 2.971–3.220 mW; wire 51,958–53,890 µm. b_m and b_ms have a synthesized netlist byte-identical to the baseline's "
      "(only the 22/44 fixed flops differ), so their deltas are placement effects.", "",
      "## Routed wire by class (tools/netlen.py, final DEF segment sums)", "",
      "| Run | total | max_reg nets | clock | rest | Δ max_reg | Δ rest |", "|---|---:|---:|---:|---:|---:|---:|"]
for tag in ("base", "b_m", "b_ms", "a_sdff"):
    r = nl[tag]
    L.append(f"| {tag} | {r['total']:,.1f} | {r['maxreg']:,.1f} | {r['clock']:,.1f} | {r['rest']:,.1f} | "
             f"{r['maxreg'] - nl['base']['maxreg']:+,.1f} | {r['rest'] - nl['base']['rest']:+,.1f} |")
L += ["", "max_reg nets = nets touching an M flop, an S flop (mac_unit S register), a max_reg exclusive-cone cell or a block cell.", "",
      "## Shipped-flow synthesis (`ll_synth.sh`; areas with cells of unknown Yosys area added from the Liberty)", ""]
p = subprocess.run([sys.executable, f"{H}/tools/statdiff.py", f"{H}/chip_runs/synth_stat/base.stat.json",
                    f"{H}/chip_runs/synth_stat/mr3s_a_sdff.stat.json", f"{H}/chip_runs/synth_stat/mr3s_b_flopcells.stat.json",
                    f"{H}/chip_runs/synth_stat/mr3s_a_sdff_aoi222.stat.json", f"{H}/chip_runs/synth_stat/mr3s_a_dff_aoi222.stat.json"],
                   capture_output=True, text=True)
L += ["```", p.stdout.rstrip(), "```", "", "Synthesis noise band (Phase 2, golden rewrites): 41,063.4–41,351.0 µm² (−52.7 / +234.9)."]
open(f"{H}/tables.md", "w").write("\n".join(L) + "\n")
print("\n".join(L))
