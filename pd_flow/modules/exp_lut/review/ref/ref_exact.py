#!/usr/bin/env python3
"""Agent 2 independent reference for exp_lut (exact rational arithmetic, no floating point).

Formulation (deliberately different from the RTL's barrel shifter + "add rounding bit" and from
the Python model's `(D + (1 << s >> 1)) >> s` and `round(255 * math.exp(...))`):

  1. Table entries: 255 * e^(-n/4) is bracketed by a rigorous rational interval
     [lo, hi] (Taylor series of e^(1/4) with an explicit remainder bound, then powered).
     W[n] = round_half_up(255 e^(-n/4)) is certified when no half-integer lies in [lo, hi].
     The table is NOT truncated at a guessed length: n runs to 40 and must reach 0 and stay 0
     (e^(-n/4) is decreasing).
  2. D' = round_half_up(D / 2^s) = floor(D / 2^s + 1/2) is never computed by shifting.
     Instead, for each s the threshold t_k(s) = ceil((k - 1/2) * 2^s) (k = 1..40) is the smallest
     D with D' >= k (Fraction arithmetic). Then W(D, s) = W[#{k : D >= t_k(s)}].
     The whole unsigned 22-bit domain is covered with no special "D >= 2^20" case: the
     reference has no out-of-range branch at all.

Outputs (in this directory):
  table.json        certified table, margins to the nearest rounding tie, thresholds per shift
  ref_thresholds.h  C header for the exhaustive Verilator sweep (exhaustive_sweep.cpp)
  ref_threshold.v   Verilog comparator-chain reference for the SAT/EQY proof (ref_sat.ys)
"""
import json
import os
from fractions import Fraction as F
from math import floor, ceil

HERE = os.path.dirname(os.path.abspath(__file__))
NMAX = 40


def exp_quarter_bounds(terms=40):
    """Rigorous bounds lo <= e^(1/4) <= hi. Taylor sum S_m of e^x at x = 1/4; the remainder is
    < x^(m+1)/(m+1)! * 1/(1 - x) for 0 < x < 1."""
    x = F(1, 4)
    s, t = F(0), F(1)
    for m in range(terms):
        s += t
        t = t * x / (m + 1)          # t is now x^(m+1)/(m+1)!
    rem = t / (1 - x)
    return s, s + rem


def table():
    lo_e, hi_e = exp_quarter_bounds()
    out = []
    for n in range(NMAX + 1):
        # 255 e^(-n/4) = 255 / (e^(1/4))^n
        lo = F(255) / hi_e ** n
        hi = F(255) / lo_e ** n
        w_lo, w_hi = floor(lo + F(1, 2)), floor(hi + F(1, 2))
        assert w_lo == w_hi, f"n={n}: interval straddles a rounding tie"
        # distance of the true value to the nearest half-integer (lower bound)
        mid = (lo + hi) / 2
        frac = mid - floor(mid)
        margin = abs(frac - F(1, 2))
        out.append({"n": n, "W": w_lo, "value_approx": float(mid), "tie_margin_approx": float(margin),
                    "interval_width": float(hi - lo)})
    return out


def thresholds(s):
    return [ceil((F(k) - F(1, 2)) * (1 << s)) for k in range(1, NMAX + 1)]


def ref_w(D, s, W, TH):
    k = sum(1 for t in TH[s] if D >= t)
    return W[k]


def main():
    tab = table()
    W = [e["W"] for e in tab]
    nz = [w for w in W if w]
    first_zero = W.index(0)
    assert all(w == 0 for w in W[first_zero:]), "table must stay 0 after the first 0"
    assert W[:first_zero] == sorted(W[:first_zero], reverse=True)
    TH = {s: thresholds(s) for s in range(16)}
    # self-checks of the threshold formulation against the definition floor(D/2^s + 1/2)
    for s in range(16):
        for k, t in enumerate(TH[s], start=1):
            assert floor(F(t, 1 << s) + F(1, 2)) >= k
            assert t == 0 or floor(F(t - 1, 1 << s) + F(1, 2)) < k
    json.dump({"W": W, "first_zero_index": first_zero, "nonzero_entries": len(nz),
               "entries": tab, "thresholds": {str(s): TH[s][:first_zero] for s in range(16)},
               "first_zero_D": {str(s): TH[s][first_zero - 1] for s in range(16)},
               "last_nonzero_D": {str(s): TH[s][first_zero - 1] - 1 for s in range(16)}},
              open(os.path.join(HERE, "table.json"), "w"), indent=1)
    # C header: thresholds up to first_zero (k = 1..first_zero), table W[0..first_zero]
    with open(os.path.join(HERE, "ref_thresholds.h"), "w") as h:
        h.write("// generated by ref_exact.py (exact rational thresholds)\n")
        h.write(f"static const int REF_NK = {first_zero};\n")
        h.write("static const unsigned REF_W[] = {" + ", ".join(map(str, W[:first_zero + 1])) + "};\n")
        h.write("static const unsigned REF_TH[16][%d] = {\n" % first_zero)
        for s in range(16):
            h.write("  {" + ", ".join(map(str, TH[s][:first_zero])) + "},\n")
        h.write("};\n")
    # Verilog reference: count of comparator hits, then a table index. No shifter, no adder on D.
    with open(os.path.join(HERE, "ref_threshold.v"), "w") as v:
        v.write("// generated by ref_exact.py: W(D,s) = W[#{k : D >= ceil((k-1/2) 2^s)}]\n")
        v.write("module ref_threshold(input wire [21:0] D, input wire [3:0] shift, output reg [7:0] W);\n")
        v.write("  reg [5:0] k;\n  always @(*) begin\n    k = 6'd0;\n    case (shift)\n")
        for s in range(16):
            conds = " + ".join(f"(D >= 22'd{t})" for t in TH[s][:first_zero])
            v.write(f"      4'd{s}: k = {conds};\n")
        v.write("    endcase\n    case (k)\n")
        for i, w in enumerate(W[:first_zero]):
            v.write(f"      6'd{i}: W = 8'd{w};\n")
        v.write("      default: W = 8'd0;\n    endcase\n  end\nendmodule\n")

    # Full reference module for EQY (formal): same ports and parameter as exp_lut, weight from the
    # threshold count (above), REGISTERED = 1 sequencing written from EXPECTED.md E7 as a single
    # next-state expression. The two state registers are named g_registered.W_r / done_r so that
    # EQY can match them with the golden's (an unbounded proof with depth-1 induction).
    with open(os.path.join(HERE, "ref_exp_lut.v"), "w") as v:
        v.write("// generated by ref_exact.py: Agent 2 formal reference for exp_lut (EXPECTED.md E1-E9)\n")
        v.write(open(os.path.join(HERE, "ref_threshold.v")).read())
        v.write("""module exp_lut #(parameter REGISTERED = 1) (
    input wire clk, input wire rst_n, input wire start,
    input wire [21:0] D, input wire [3:0] shift,
    output wire done, output wire [7:0] W);
  wire [7:0] f;
  ref_threshold t(.D(D), .shift(shift), .W(f));
  generate if (REGISTERED != 0) begin : g_registered
    reg done_r; reg [7:0] W_r;
    always @(posedge clk) begin
      done_r <= rst_n & start;
      W_r <= ({8{rst_n}} & ((start ? f : W_r)));
    end
    assign done = done_r; assign W = W_r;
  end else begin : g_comb
    assign done = start; assign W = f;
  end endgenerate
endmodule
""")
    print("W =", W[:first_zero + 1], "first zero at D' =", first_zero)
    print("closest ties:", sorted(((e["tie_margin_approx"], e["n"], e["value_approx"]) for e in tab[1:first_zero + 2]))[:4])
    for s in range(16):
        print(f"s={s:2d} t_1={TH[s][0]:>7d} t_25={TH[s][first_zero-1]:>8d} (D >= t_25 -> 0)")


if __name__ == "__main__":
    main()
